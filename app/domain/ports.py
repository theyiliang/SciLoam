"""Dependency-inversion contracts for research use cases."""
from __future__ import annotations
from typing import Callable, ContextManager, Protocol

from .models import Record


class ResearchRepository(Protocol):
    """Records are detached values; filtering arguments are data, never SQL."""
    def get(self, entity: str, key: str) -> Record | None: ...
    def find(self, entity: str, **filters) -> Record | None: ...
    def list(self, entity: str, **filters) -> list[Record]: ...
    def add(self, entity: str, record: Record) -> None: ...
    def update(self, entity: str, key: str, changes: Record) -> None: ...
    def delete_where(self, entity: str, **filters) -> int: ...
    def set_membership(self, space_id: str, user_id: str, role: str) -> None: ...
    def membership(self, space_id: str, user_id: str) -> str | None: ...
    def space_members(self, space_id: str) -> list[Record]: ...
    def member_space_ids(self, user_id: str) -> list[str]: ...
    def version_details(self, version_id: str) -> Record | None: ...
    def version_metadata(self, document_id: str) -> list[Record]: ...
    def document_active_head(self, document_id: str) -> Record | None: ...
    def set_document_head(self, document_id: str, version_id: str) -> None: ...
    def active_version_details(self, version_id: str) -> Record | None: ...
    def version_references(self, version_id: str) -> list[Record]: ...
    def next_version_number(self, document_id: str) -> int: ...
    def lineage_authors(self, version_id: str) -> set[str]: ...
    def searchable_versions(self, space_id: str) -> list[Record]: ...
    def save_login_failure(self, email: str, record: Record) -> None: ...


class ResearchUnitOfWork(Protocol):
    repository: ResearchRepository

    def __enter__(self) -> "ResearchUnitOfWork": ...
    def __exit__(self, exc_type, exc_value, traceback) -> bool | None: ...


UnitOfWorkFactory = Callable[[], ContextManager[ResearchUnitOfWork]]
Clock = Callable[[], float]


class ResearchSecurity(Protocol):
    def hash_password(self, password: str) -> str: ...
    def verify_password(self, password: str, encoded: str) -> bool: ...
    def new_token(self) -> str: ...
    def hash_token(self, token: str) -> str: ...
